#!/usr/bin/env python3
"""Quests an NPC can't have in progress together (server/content/quest-exclusions.json).

The client runs NPC conversations itself and takes the first <start> block whose conditions hold. Many conversations
check "quest X in progress" (QUEST_CURRENT X, maybe with a class) before the blocks that turn in an older quest Y at the
same NPC, so holding X hides Y's hand-in: Eanan's Meteoric Astral Greaves hid the Warden Eanan disc turn-in. On live the
server never let both be held; here X isn't offered while Y is in progress, and a taken X with nothing done is dropped at
log-in (GameServer.Quests DropBlockingQuests).

  python3 scripts/gen-quest-exclusions.py [build]
"""
import collections, json, os, re, sys

sys.path.insert(0, os.path.dirname(__file__))
import chdata

build = sys.argv[1] if len(sys.argv) > 1 else "24928510"
quests = json.load(open(f"{chdata.HOME}/extracted/{build}/world.json", encoding="utf-8-sig"))["quests"]
assets = chdata.text_assets(chdata.textfiles_bundle(build), rb"cv_[A-Za-z0-9_]+")


def plain(q):
    return q is not None and not q["repeatable"] and not q["seasonal"] and q["archetype"] == "NoRepeat"


balance = json.load(open(f"{chdata.HOME}/extracted/{build}/balance-client.json", encoding="utf-8-sig"))
conv_ids = {c["Filename"]: c["ConversationId"] for c in balance["ConversationLookupsTemplates"]}
adds = collections.defaultdict(set)  # quest → conversations that start it (QUEST_ADD)
hides = collections.defaultdict(lambda: collections.defaultdict(set))  # X → Y → conversations
for name, raw in assets.items():
    text = re.sub(r"<!--.*?-->", "", raw.decode("utf-8", "replace") if isinstance(raw, bytes) else raw, flags=re.S)
    for q in re.findall(r"QUEST_ADD (\d+)", text):
        adds[int(q)].add(name)
    conds = [re.findall(r"<startCondition>\s*(.*?)\s*</startCondition>", b) for b in re.findall(r"<start>(.*?)</start>", text, flags=re.S)]
    # Quests a block checks together are meant to be held together (Torbin's Sea Chart is a side quest of Broon's
    # Enchanted: "STAGE_COMPLETE 478 1" with "STAGE_AVAILABLE 106 4"), so neither hides the other.
    together = set()
    for cs in conds:
        ids = {int(m.group(1)) for c in cs if (m := re.match(r"[A-Z_]+ (\d+)", c))}
        together.update((a, b) for a in ids for b in ids if a != b)
    for i, cs in enumerate(conds):
        current = [c.split()[1] for c in cs if re.match(r"QUEST_CURRENT \d+$", c)]
        # Only a block that fires on "X in progress" alone (class checks aside) swallows every block after it.
        if len(current) != 1 or any(not (c.startswith("QUEST_CURRENT ") or c.startswith("CLASS ")) for c in cs):
            continue
        x = int(current[0])
        for later in conds[i + 1:]:
            for c in later:
                m = re.match(r"(STAGE_AVAILABLE|STAGE_COMPLETE|QUEST_CURRENT) (\d+)$", c)
                if m and int(m.group(2)) != x and (x, int(m.group(2))) not in together:
                    hides[x][int(m.group(2))].add(name)

# Quests the data gives no giver are never offered (GameServer.Quests QuestLists), though a conversation starts them:
# Kyna's Crests of the Serpent (the Frozen gloves). Give them that conversation.
givers = {}
for q, convs in adds.items():
    info = quests.get(str(q))
    if plain(info) and info["giver"] is None and (ids := sorted(conv_ids[c] for c in convs if c in conv_ids)):
        givers[q] = ids[0]

out = []
for x in sorted(hides):
    if not plain(quests.get(str(x))):
        continue
    ys = [[y, quests[str(y)]["name"]] for y in sorted(hides[x]) if plain(quests.get(str(y)))]
    if ys:
        out.append({"id": x, "name": quests[str(x)]["name"], "conversations": sorted(set().union(*hides[x].values())), "notWhileActive": ys})
done = {e["id"] for e in out}
for e in out:
    if e["id"] in givers: e["giver"] = givers[e["id"]]
for q in sorted(set(givers) - done):
    out.append({"id": q, "name": quests[str(q)]["name"], "giver": givers[q]})
out.sort(key=lambda e: e["id"])
doc = {"_comment": "Generated by scripts/gen-quest-exclusions.py from the client's conversations; don't edit by hand (owner's rules go in "
       "quest-requirements.json, which takes notWhileActive too). A quest isn't offered while one of its notWhileActive quests is in "
       "progress, because the NPC checks this quest before that one's turn-in; one taken with nothing done is dropped at log-in. "
       "giver: the conversation that starts a quest the data gives no giver, so the server offers it.",
       "build": build, "quests": out}
path = os.path.join(os.path.dirname(__file__), "..", "server", "content", "quest-exclusions.json")
json.dump(doc, open(path, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
print(f"{len(out)} quests -> {os.path.normpath(path)}")
