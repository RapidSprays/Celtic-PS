#!/usr/bin/env python3
"""Generate docs/opcode-map.md from an AsmIndex enums.json (NetworkCommandType + NetworkCommandStatus)."""
import json, sys, collections
src, build = sys.argv[1], sys.argv[2]
enums = {e["name"]: e for e in json.load(open(src))["enums"]}
cmd = enums["Assets.Engine.Enums.NetworkCommandType"]
out = [f"# Opcode map: build {build}", "",
       f"Generated by `scripts/gen-opcode-map.py` from AsmIndex output. **Observed** (enum metadata in `Assembly-CSharp.dll`).",
       "", f"`NetworkCommandType`: {cmd['underlying']}, {cmd['count']} members, sent as a Lidgren varuint at the start of every message (both directions).",
       "Status column: implementation state in our server (`-` = not yet).", ""]
groups = collections.OrderedDict()
for m in sorted(cmd["members"], key=lambda m: m["value"]):
    groups.setdefault(m["value"] // 1000, []).append(m)
for g, ms in groups.items():
    out += [f"## {g*1000}–{g*1000+999}", "", "| Value | Name | Status |", "|---|---|---|"]
    out += [f"| {m['value']} | {m['name']} | - |" for m in ms]
    out.append("")
st = enums["Assets.Engine.Enums.NetworkCommandStatus"]
out += ["## NetworkCommandStatus (first byte of most replies)", "", "| Value | Name |", "|---|---|"]
out += [f"| {m['value']} | {m['name']} |" for m in st["members"]]
open("docs/opcode-map.md", "w").write("\n".join(out) + "\n")
print(f"{cmd['count']} opcodes in {len(groups)} groups")
